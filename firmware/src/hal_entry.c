/*
 * Melon Disease Edge Classifier — main inference loop on EK-RA8P1.
 *
 * Hardware  : Renesas RA8P1 (Cortex-M85 @ 1GHz + Ethos-U55 @ 500MHz, 256MAC)
 * Toolchain : e² studio + FSP (Google TFLM Core + CMSIS-NN + ARM Ethos-U driver)
 * Output    : SEGGER RTT (J-Link on-board, no extra wiring)
 *
 * Flow per inference:
 *   1) preprocess uint8 HWC → float NCHW + ImageNet normalize
 *   2) memcpy into model input buffer
 *   3) reset PMU counters
 *   4) RunModel(false)   — calls CPU→NPU→CPU subgraphs
 *   5) read CPU cycles + NPU active/idle/axi counters
 *   6) argmax + softmax → print top-1 class with confidence + cycles
 */

